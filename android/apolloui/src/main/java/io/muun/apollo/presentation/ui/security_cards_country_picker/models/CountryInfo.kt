data class CountryInfo private constructor(
    val code: MarketplaceCountryCode,
    @StringRes private val nameRes: Int,
    val flagEmoji: String,
) {

    constructor(code: MarketplaceCountryCode) : this(code, nameOf(code), flagOf(code))

    companion object {

        private fun nameOf(code: MarketplaceCountryCode): Int {
            return COUNTRY_NAMES_AND_FLAGS_MAP.getValue(code).first
        }

        private fun flagOf(code: MarketplaceCountryCode): String {
            return COUNTRY_NAMES_AND_FLAGS_MAP.getValue(code).second
        }
    }

    fun name(context: Context): String {
        return context.getString(nameRes)
    }
}

